/**
 * Allows future dynamic expansion of the vocabulary bank at runtime.
 */
export function registerCustomWords(entries: WordEntry[]): number {
  let added = 0;
  for (const entry of entries) {
    const trimmed = entry.word.trim();
    if (!trimmed) continue;
    if (!WORD_MAP.has(trimmed)) {
      const normalized: WordEntry = {
        word: trimmed,
        category: entry.category,
        tags: Array.from(new Set([entry.category, ...entry.tags])),
        relatedClues: Array.from(new Set([entry.category, ...entry.relatedClues])),
      };
      WORD_DICTIONARY.push(normalized);
      WORD_MAP.set(trimmed, normalized);
      added++;
    }
  }
  return added;
}
