const buildWordDictionary = (): WordEntry[] => {
  const map = new Map<string, WordEntry>();

  (Object.keys(RAW_CATEGORY_CLUSTERS) as WordCategory[]).forEach((category) => {
    const clusters = RAW_CATEGORY_CLUSTERS[category];
    for (const cluster of clusters) {
      for (const rawWord of cluster.words) {
        const word = rawWord.trim();
        if (!word) continue;
        const existing = map.get(word);
        if (existing) {
          existing.tags = Array.from(new Set([...existing.tags, ...cluster.tags]));
          existing.relatedClues = Array.from(new Set([...existing.relatedClues, ...cluster.clues]));
        } else {
          map.set(word, {
            word,
            category,
            tags: Array.from(new Set([category, ...cluster.tags])),
            relatedClues: Array.from(new Set([category, ...cluster.clues])),
          });
        }
      }
    }
  });

  for (const extra of EXTRA_UNIQUE_WORDS) {
    if (!map.has(extra.word)) {
      map.set(extra.word, {
        word: extra.word,
        category: extra.category,
        tags: Array.from(new Set([extra.category, ...extra.tags])),
        relatedClues: Array.from(new Set([extra.category, ...extra.clues])),
      });
    }
  }

  return Array.from(map.values());
};

